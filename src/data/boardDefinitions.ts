import type { BoardSquare, RentSchedule } from "../types/game";

function rent(
  base: number,
  one: number,
  two: number,
  three: number,
  four: number,
  hotel: number,
): RentSchedule {
  return {
    base,
    oneHouse: one,
    twoHouses: two,
    threeHouses: three,
    fourHouses: four,
    hotel,
  };
}

function prop(
  id: string,
  boardIndex: number,
  name: string,
  type: BoardSquare["type"],
  colorGroup: BoardSquare["colorGroup"],
  price: number,
  r: RentSchedule,
  houseCost: number,
): Omit<BoardSquare, "ownerId" | "houses"> {
  return {
    id,
    boardIndex,
    name,
    type,
    colorGroup,
    price,
    rent: r,
    houseCost,
  };
}

